--Q7. What percentage of total revenue comes from the Top 10 customers?
WITH total_percentage AS (
SELECT SUM(p.price*od.quantity) AS total_revenue,c.customer_id
FROM customerp2 c
JOIN orderp2 o ON c.customer_id=o.customer_id
JOIN orderdetailsp2 od ON o.order_id=od.order_id
JOIN productp2 p ON p.product_id=od.product_id
GROUP BY 2
ORDER BY total_revenue desc LIMIT 10)
SELECT SUM(total_revenue)*100.00/(SELECT SUM(p.price*od.quantity) AS total_revenue
FROM orderp2 o
JOIN orderdetailsp2 od ON o.order_id=od.order_id
JOIN productp2 p ON p.product_id=od.product_id) AS percentage_top_10
FROM total_percentage;

--Q8. What is the average order value for each customer?
SELECT
    c.customer_id,
    c.customer_name,
    SUM(p.price * od.quantity) / COUNT(DISTINCT o.order_id) AS average_order_value
FROM customerp2 c
JOIN orderp2 o ON c.customer_id = o.customer_id
JOIN orderdetailsp2 od ON o.order_id = od.order_id
JOIN productp2 p ON p.product_id = od.product_id
GROUP BY c.customer_id, c.customer_name
ORDER BY average_order_value DESC;  

