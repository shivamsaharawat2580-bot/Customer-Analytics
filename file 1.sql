-- 1. Customers
CREATE TABLE customerp2 (
    customer_id INT PRIMARY KEY,
    customer_name VARCHAR(100),
    gender VARCHAR(20),
    age INT,
    city VARCHAR(100),
    state VARCHAR(100),
    customer_segment VARCHAR(50),
	signup_date DATE
);

