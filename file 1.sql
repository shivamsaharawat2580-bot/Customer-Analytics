-- 2. Products
CREATE TABLE productp2 (
    product_id INT PRIMARY KEY,
    product_name VARCHAR(150),
    category VARCHAR(100),
    brand VARCHAR(100),
    price NUMERIC(12,2)
);


-- 3. Orders
CREATE TABLE orderp2 (
    order_id INT PRIMARY KEY,
    customer_id INT,
    order_date DATE,
    sales_channel VARCHAR(50),

    CONSTRAINT fk_order_customer
        FOREIGN KEY (customer_id)
        REFERENCES customerp2(customer_id)
);


-- 4. Order Details
CREATE TABLE orderdetailsp2 (
    order_detail_id INT PRIMARY KEY,
    order_id INT,
    product_id INT,
    quantity INT,

    CONSTRAINT fk_orderdetail_order
        FOREIGN KEY (order_id)
        REFERENCES orderp2(order_id),

    CONSTRAINT fk_orderdetail_product
        FOREIGN KEY (product_id)
        REFERENCES productp2(product_id)
);


-- 5. Returns
CREATE TABLE returnp2 (
    return_id INT PRIMARY KEY,
    order_id INT,
    return_date DATE,
    return_reason VARCHAR(100),

    CONSTRAINT fk_return_order
        FOREIGN KEY (order_id)
        REFERENCES orderp2(order_id)
);


-- 6. Support Tickets
CREATE TABLE ticketp2 (
    ticket_id INT PRIMARY KEY,
    customer_id INT,
    ticket_date DATE,
    issue_type VARCHAR(100),
    priority VARCHAR(50),
    resolution_hours NUMERIC(10,2),
    customer_satisfaction NUMERIC(5,2),

    CONSTRAINT fk_support_customer
        FOREIGN KEY (customer_id)
        REFERENCES customerp2(customer_id)
);


-- 7. Customer Loyalty
CREATE TABLE loyaltyp2 (
    loyalty_id INT PRIMARY KEY,
    customer_id INT,
    loyalty_tier VARCHAR(50),
    points INT,
    enrollment_date DATE,

    CONSTRAINT fk_loyalty_customer
        FOREIGN KEY (customer_id)
        REFERENCES customerp2(customer_id)
);

