--Q17. What is the overall customer/order return rate?
SELECT COUNT(DISTINCT r.order_id)*100.0/COUNT(DISTINCT o.order_id) AS return_rate
FROM orderp2 o
LEFT JOIN returnp2 r ON o.order_id=r.order_id;

--Q18. Which customer segment has the highest return rate?

SELECT c.customer_segment,COUNT(DISTINCT r.order_id)*100.0/COUNT(DISTINCT o.order_id) AS return_rate
FROM orderp2 o
LEFT JOIN returnp2 r ON o.order_id=r.order_id
JOIN customerp2 c ON c.customer_id=o.customer_id
GROUP BY 1
ORDER BY return_rate DESC LIMIT 1; 



