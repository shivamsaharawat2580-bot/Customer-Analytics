--How many total customers are there?
SELECT count(customer_id) AS total_customer
FROM customerp2;

--How many customers are active, meaning they placed at least one order?
SELECT COUNT(DISTINCT customer_id) AS total_active_customer
FROM orderp2;

--How many repeat customers are there?
SELECT customer_id,count(order_id) AS total_order
FROM orderp2
GROUP BY 1 
HAVING  COUNT(customer_id)>1
ORDER BY total_order desc; 

--What is the repeat customer rate?
WITH repeat_customers AS (
    SELECT customer_id
    FROM orderp2
    GROUP BY customer_id
    HAVING COUNT(order_id) > 1
)
SELECT
    COUNT(*) * 100.0 /
    (SELECT COUNT(*) FROM customerp2) AS repeat_customer_rate_pct
FROM repeat_customers;

