--Q11. Which customer segment has the highest AOV?
SELECT c.customer_segment,SUM(p.price*od.quantity)/COUNT(DISTINCT o.order_id) AS average_order_value
FROM customerp2 c
JOIN orderp2 o ON c.customer_id=o.customer_id
JOIN orderdetailsp2 od ON o.order_id=od.order_id
JOIN productp2 p ON p.product_id=od.product_id
GROUP BY 1
ORDER BY average_order_value DESC LIMIT 1; 

--Q12. Which customer segment has the highest purchase frequency?
SELECT c.customer_segment,COUNT(DISTINCT o.order_id)*1.0/COUNT(DISTINCT c.customer_id) AS total_order
FROM customerp2 c 
JOIN orderp2 o ON o.customer_id=c.customer_id
GROUP BY 1
ORDER BY total_order DESC LIMIT 1; 


